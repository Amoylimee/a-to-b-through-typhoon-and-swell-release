#!/usr/bin/env python3
"""Emit one cleaning configuration per year, with identical thresholds by construction.

The cleaning step reads a single flat YAML through `CLEAN_AIS_CONFIG`, so five years
need five files. Writing them by hand would make "the same configuration for every
year" a claim about my care rather than a property of the artefact, and a single
mistyped threshold in one year would be invisible in the results. So the thresholds
live once, here, and the only thing that varies between the emitted files is which
year's shards go in and where its outputs go.

## Where these values come from

They are not new. The accepted 2021 and 2025 products were cleaned with exactly these
thresholds, recovered from two independent places that agree:

- `P3_construct_baseline_routes/config.yaml` in the archived shipping-2 project, the
  file those runs actually read;
- the per-shard `_stats.json` written at run time, which records
  `gap_threshold_hours: 4.0` and `drift_multiplier: 1.5` for both 2021 and 2025.

That legacy config was switched between years by editing `input_dir` and `output_dir`
only; no threshold ever varied by year. So running five years on one configuration
continues the accepted method rather than changing it.

## The 4-hour gap threshold and 2024

A trajectory is split where the signal is lost for longer than `gap.threshold_hours`.
reference AIS's observation density steps down about 20% on 2024-04-15, so a fixed threshold
splits post-April 2024 trajectories more often than earlier ones — for observational
rather than navigational reasons.

Holding the threshold fixed is the deliberate choice. Segmenting it at the break would
put a man-made discontinuity inside the data and defeat the point of running one
method over five years; leaving it fixed keeps the cleaning uniform and hands the
observation change to the analysis, where a break indicator can absorb it explicitly.
The same 4.0 hours is also what port-call detection uses as its AIS-gap evidence
threshold, so the two layers stay aligned.
"""

from __future__ import annotations

import argparse
from pathlib import Path

CONFIG_DIR = Path(__file__).resolve().parent
CODING_ROOT = CONFIG_DIR.parents[3]

YEARS = (2021, 2022, 2023, 2024, 2025)

# vessel specs are published for these years only; the others reuse 2021, whose
# fields here - ship type and service speed - do not move year to year
SPECS_YEARS = (2021, 2025)

SHARED = """\
gap:
  threshold_hours: 4.0
  sample_shards: 5

drift:
  speed_multiplier: 1.5

audit:
  residual_speed_multiplier: 1.1
  residual_speed_min_excess_knots: 2.0
  reported_sog_multiplier: 1.5
  reported_sog_min_excess_knots: 5.0
  flag_row_limit_per_shard: 200000
  top_vessel_limit: 200

chunking:
  target_rows: 200000

parallel:
  max_workers: 24

report:
  sample_gap_quantiles:
    - 0.9
    - 0.95
    - 0.99
    - 0.995
    - 0.999
"""

HEADER = """\
# Generated by build_clean_ais_configs.py - do not edit by hand.
#
# Thresholds are identical across 2021-2025 and carry over unchanged from the
# accepted 2021/2025 runs, confirmed against both the archived shipping-2
# config.yaml and the gap_threshold_hours / drift_multiplier recorded in the
# per-shard _stats.json of those runs.
"""


def specs_year(year: int) -> int:
    return year if year in SPECS_YEARS else 2021


def render(year: int) -> str:
    specs = specs_year(year)
    note = "" if specs == year else f"  # reused: no {year} specs are published\n"
    return (
        HEADER
        + f"\ninput_dir: \"data/processed/products/unified_ais_shards/{year}\"\n"
        # the mask stage recovers the year by matching ais_cleaning_(\\d{4}) against
        # this path, so the directory name has to carry it in that exact form
        + f"output_dir: \"data/processed/clean_ais_tracks/ais_cleaning_{year}\"\n"
        + f"specs_table_path: \"data/legacy_inputs/vessel_specs_{specs}/vessel_specs_by_mmsi_{specs}.csv\"\n"
        + note
        + "\n"
        + SHARED
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if any file is stale")
    args = parser.parse_args()

    stale = []
    for year in YEARS:
        path = CONFIG_DIR / f"clean_ais_{year}.yaml"
        text = render(year)
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.name)
            continue
        path.write_text(text)
        print(f"wrote {path.relative_to(CODING_ROOT)}")

    if args.check:
        if stale:
            print("stale or missing: " + ", ".join(stale))
            return 3
        print(f"all {len(YEARS)} configs match the generator")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
